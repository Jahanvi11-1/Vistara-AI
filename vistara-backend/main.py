# GEMINI ANALYSIS
# ============================================================================

async def analyze_with_gemini(
    contract_text: str,
    filename: str,
    pages: List[ExtractedPage],
) -> ContractReport:

    # ------------------------------------------------------------------------
    # Check API key
    # ------------------------------------------------------------------------

    api_key = os.getenv("GEMINI_API_KEY")

    if not api_key:
        raise HTTPException(
            status_code=500,
            detail=(
                "GEMINI_API_KEY is missing. "
                "Add your Google AI Studio API key to the .env file."
            ),
        )

    try:

        # --------------------------------------------------------------------
        # Initialize Gemini client
        # --------------------------------------------------------------------

        client = genai.Client(
            api_key=api_key,
        )

        # --------------------------------------------------------------------
        # Build Gemini input
        #
        # IMPORTANT:
        # We no longer blindly truncate at 15,000 characters.
        #
        # Page-aware text is supplied so Gemini can understand the entire
        # available contract input within the model's context capacity.
        # --------------------------------------------------------------------

        analysis_text = contract_text

        user_prompt = (
            f"Filename: {filename}\n\n"
            f"Contract Text:\n{analysis_text}"
        )

        # --------------------------------------------------------------------
        # Structured output schema
        #
        # evidence_verified / match_confidence / matched_page are deliberately
        # NOT part of Gemini's schema.
        #
        # Vistara calculates those after Gemini responds.
        # --------------------------------------------------------------------

        response_schema = {
            "type": "OBJECT",
            "properties": {
                "filename": {
                    "type": "STRING",
                },
                "overall_score": {
                    "type": "INTEGER",
                },
                "risk_level": {
                    "type": "STRING",
                    "enum": [
                        "High",
                        "Medium",
                        "Low",
                    ],
                },
                "high_risk_count": {
                    "type": "INTEGER",
                },
                "medium_risk_count": {
                    "type": "INTEGER",
                },
                "low_risk_count": {
                    "type": "INTEGER",
                },
                "flagged_clauses": {
                    "type": "ARRAY",
                    "items": {
                        "type": "OBJECT",
                        "properties": {
                            "clause_text": {
                                "type": "STRING",
                            },
                            "severity": {
                                "type": "STRING",
                                "enum": [
                                    "High",
                                    "Medium",
                                    "Low",
                                ],
                            },
                            "category": {
                                "type": "STRING",
                            },
                            "plain_explanation": {
                                "type": "STRING",
                            },
                            "worst_case_scenario": {
                                "type": "STRING",
                            },
                        },
                        "required": [
                            "clause_text",
                            "severity",
                            "category",
                            "plain_explanation",
                            "worst_case_scenario",
                        ],
                    },
                },
            },
            "required": [
                "filename",
                "overall_score",
                "risk_level",
                "high_risk_count",
                "medium_risk_count",
                "low_risk_count",
                "flagged_clauses",
            ],
        }

        # --------------------------------------------------------------------
        # Gemini request
        # --------------------------------------------------------------------

        response = client.models.generate_content(
            model=GEMINI_MODEL,
            contents=user_prompt,
            config=types.GenerateContentConfig(
                system_instruction=SYSTEM_PROMPT,
                temperature=0.2,
                response_mime_type="application/json",
                response_schema=response_schema,
            ),
        )

        # --------------------------------------------------------------------
        # Get response text
        # --------------------------------------------------------------------

        if not response.text:
            raise HTTPException(
                status_code=500,
                detail="Gemini returned an empty response.",
            )

        # --------------------------------------------------------------------
        # Parse JSON
        # --------------------------------------------------------------------

        try:
            report_data = json.loads(
                response.text
            )

        except json.JSONDecodeError as e:
            print(
                "JSON Parsing Error:",
                e,
            )
            print(
                "Gemini response:",
                response.text,
            )

            raise HTTPException(
                status_code=500,
                detail="Gemini returned invalid JSON.",
            )

        # --------------------------------------------------------------------
        # Always trust actual uploaded filename
        # --------------------------------------------------------------------

        report_data["filename"] = filename

        # --------------------------------------------------------------------
        # Validate Gemini response using Pydantic
        # --------------------------------------------------------------------

        report = ContractReport(
            **report_data
        )

        # --------------------------------------------------------------------
        # IMPORTANT:
        #
        # Verify Gemini's evidence against the ACTUAL supplied document.
        #
        # This happens for:
        # - PDFs
        # - raw text
        # - other readable text files
        # --------------------------------------------------------------------

        verified_report = verify_report_evidence(
            report=report,
            pages=pages,
        )

        return verified_report

    # ------------------------------------------------------------------------
    # HTTP errors
    # ------------------------------------------------------------------------

    except HTTPException:
        raise

    # ------------------------------------------------------------------------
    # Gemini/API errors
    # ------------------------------------------------------------------------

    except Exception as e:

        error_text = str(e)

        print(
            "Gemini API Error:\n"
            f"{traceback.format_exc()}"
        )

        # --------------------------------------------------------------------
        # Quota / rate limit
        # --------------------------------------------------------------------

        if (
            "429" in error_text
            or "RESOURCE_EXHAUSTED" in error_text
            or "quota" in error_text.lower()
        ):
            raise HTTPException(
                status_code=429,
                detail=(
                    "Gemini API quota has been exceeded. "
                    "Please check your Google AI Studio project quota "
                    "or try again later."
                ),
            )

        # --------------------------------------------------------------------
        # Authentication
        # --------------------------------------------------------------------

        if (
            "401" in error_text
            or "UNAUTHENTICATED" in error_text
            or "authentication" in error_text.lower()
        ):
            raise HTTPException(
                status_code=401,
                detail=(
                    "Gemini API authentication failed. "
                    "Check that GEMINI_API_KEY in .env contains "
                    "a valid Google AI Studio API key."
                ),
            )

        # --------------------------------------------------------------------
        # General error
        # --------------------------------------------------------------------

        raise HTTPException(
            status_code=500,
            detail=(
                f"Gemini API analysis failed: "
                f"{error_text}"
            ),
        )


