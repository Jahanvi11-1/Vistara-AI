def extract_text_input(
    text: str,
) -> List[ExtractedPage]:
    """
    Convert raw text input into the same internal page representation.

    Raw text has no real PDF page information, so it is treated as one
    logical page.
    """

    return [
        ExtractedPage(
            page_number=1,
            text=text.strip(),
        )
    ]


# ============================================================================
# EVIDENCE VERIFICATION
# ============================================================================

def exact_normalized_match(
    clause_text: str,
    document_text: str,
) -> bool:
    """
    Check whether the Gemini clause exists in the document after
    formatting normalization.
    """

    clause = normalize_text(clause_text)
    document = normalize_text(document_text)

    if not clause or not document:
        return False

    return clause in document


def tolerant_exact_match(
    clause_text: str,
    document_text: str,
) -> bool:
    """
    More tolerant exact comparison.

    Useful when punctuation or line formatting differs.
    """

    clause = normalize_for_matching(clause_text)
    document = normalize_for_matching(document_text)

    if not clause or not document:
        return False

    return clause in document


# ============================================================================
# FUZZY MATCHING HELPERS
# ============================================================================

def tokenize_matching_text(
    text: str,
) -> List[str]:
    normalized = normalize_for_matching(text)

    if not normalized:
        return []

    return normalized.split()


def similarity(
    a: str,
    b: str,
) -> float:
    if not a or not b:
        return 0.0

    return SequenceMatcher(
        None,
        a,
        b,
    ).ratio()


def fuzzy_clause_match(
    clause_text: str,
    document_text: str,
) -> float:
    """
    Find a likely location of the Gemini clause in document text.

    Returns a confidence score from 0.0 to 1.0.

    This is deliberately conservative:
    it does not treat a tiny 2-3 word phrase as a valid clause.
    """

    clause_tokens = tokenize_matching_text(
        clause_text
    )

    document_tokens = tokenize_matching_text(
        document_text
    )

    if not clause_tokens or not document_tokens:
        return 0.0

    # Extremely short Gemini evidence is unsafe to locate.
    if len(clause_tokens) < 8:
        return 0.0

    clause_joined = " ".join(
        clause_tokens
    )

    target_length = len(clause_tokens)

    # We search around the expected clause length.
    min_window = max(
        8,
        int(target_length * 0.80),
    )

    max_window = min(
        len(document_tokens),
        max(
            min_window,
            int(target_length * 1.20),
        ),
    )

    best_score = 0.0

    # ------------------------------------------------------------------------
    # Use the first and last words as anchors.
    #
    # This prevents generic phrases such as:
    #
    #   "before the expiration"
    #
    # from becoming the basis of a match.
    # ------------------------------------------------------------------------

    anchor_size = min(
        6,
        max(
            3,
            len(clause_tokens) // 4,
        ),
    )

    start_anchor = " ".join(
        clause_tokens[:anchor_size]
    )

    end_anchor = " ".join(
        clause_tokens[-anchor_size:]
    )

    # ------------------------------------------------------------------------
    # Find candidate locations using the beginning anchor.
    # ------------------------------------------------------------------------

    candidate_starts: List[int] = []

    for index in range(
        0,
        len(document_tokens) - anchor_size + 1,
    ):
        candidate = " ".join(
            document_tokens[
                index:index + anchor_size
            ]
        )

        anchor_score = similarity(
            start_anchor,
            candidate,
        )

        if anchor_score >= 0.72:
            candidate_starts.append(index)

    # ------------------------------------------------------------------------
    # If no strong beginning anchor exists, don't blindly scan every phrase.
    # ------------------------------------------------------------------------

    if not candidate_starts:
        return 0.0

    for start_index in candidate_starts:
        for window_size in range(
            min_window,
            max_window + 1,
        ):
            end_index = (
                start_index + window_size
            )

            if end_index > len(document_tokens):
                break

            candidate_tokens = document_tokens[
                start_index:end_index
            ]

            candidate_text = " ".join(
                candidate_tokens
            )

            full_score = similarity(
                clause_joined,
                candidate_text,
            )

            if full_score < best_score:
                continue

            # --------------------------------------------------------------
            # End-anchor verification.
            # --------------------------------------------------------------

            if len(candidate_tokens) >= anchor_size:
                candidate_end_anchor = " ".join(
                    candidate_tokens[
                        -anchor_size:
                    ]
                )

                end_score = similarity(
                    end_anchor,
                    candidate_end_anchor,
                )
            else:
                end_score = 0.0

            # --------------------------------------------------------------
            # Combined confidence.
            # --------------------------------------------------------------

            combined_score = (
                (full_score * 0.70)
                + (end_score * 0.30)
            )

            if combined_score > best_score:
                best_score = combined_score

    return best_score


# ============================================================================
# VERIFY CLAUSE AGAINST DOCUMENT
# ============================================================================

def verify_clause_evidence(
    clause_text: str,
    pages: List[ExtractedPage],
) -> tuple[bool, float, Optional[int]]:
    """
    Verify Gemini's clause against the actual supplied document.

    Returns:

        evidence_verified
        confidence
        matched_page
    """

    if not clause_text.strip():
        return False, 0.0, None

    # ------------------------------------------------------------------------
    # 1. Strong exact match.
    # ------------------------------------------------------------------------

    for page in pages:
        if not page.text.strip():
            continue

        if exact_normalized_match(
            clause_text,
            page.text,
        ):
            return True, 1.0, page.page_number

    # ------------------------------------------------------------------------
    # 2. Tolerant exact match.
    # ------------------------------------------------------------------------

    for page in pages:
        if not page.text.strip():
            continue

        if tolerant_exact_match(
            clause_text,
            page.text,
        ):
            return True, 0.98, page.page_number

    # ------------------------------------------------------------------------
    # 3. Controlled fuzzy matching.
    #
    # We do NOT accept weak fuzzy matches.
    # ------------------------------------------------------------------------

    best_confidence = 0.0
    best_page: Optional[int] = None

    for page in pages:
        if not page.text.strip():
            continue

        score = fuzzy_clause_match(
            clause_text,
            page.text,
        )

        if score > best_confidence:
            best_confidence = score
            best_page = page.page_number

    # ------------------------------------------------------------------------
    # Conservative verification threshold.
    #
    # This is intentionally not based on any specific document.
    # ------------------------------------------------------------------------

    if best_confidence >= 0.88:
        return (
            True,
            round(best_confidence, 4),
            best_page,
        )

    return (
        False,
        round(best_confidence, 4),
        best_page,
    )


# ============================================================================
# VERIFY COMPLETE REPORT
# ============================================================================

def verify_report_evidence(
    report: ContractReport,
    pages: List[ExtractedPage],
) -> ContractReport:
    """
    Verify every Gemini-generated risk finding.

    Gemini determines the risk.

    This function only verifies whether the evidence exists in the
    actual supplied document.
    """

    verified_clauses: List[ClauseRisk] = []

    print(
        "========================================"
    )
    print(
        "VISTARA EVIDENCE VERIFICATION STARTED"
    )
    print(
        f"Clauses to verify: "
        f"{len(report.flagged_clauses)}"
    )
    print(
        "========================================"
    )

    for index, clause in enumerate(
        report.flagged_clauses,
        start=1,
    ):
        verified, confidence, page_number = (
            verify_clause_evidence(
                clause_text=clause.clause_text,
                pages=pages,
            )
        )

        updated_clause = clause.model_copy(
            update={
                "evidence_verified": verified,
                "match_confidence": confidence,
                "matched_page": page_number,
            }
        )

        verified_clauses.append(
            updated_clause
        )

        print(
            f"Clause {index}: "
            f"[{clause.severity.value}] "
            f"verified={verified} "
            f"confidence={confidence:.3f} "
            f"page={page_number}"
        )

    print(
        "========================================"
    )
    print(
        "VISTARA EVIDENCE VERIFICATION FINISHED"
    )
    print(
        "========================================"
    )

    return report.model_copy(
        update={
            "flagged_clauses": verified_clauses
        }
    )


