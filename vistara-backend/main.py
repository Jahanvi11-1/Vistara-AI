# ============================================================================
# TEXT NORMALIZATION
# ============================================================================

def normalize_text(text: str) -> str:
    """
    Normalize text for evidence comparison.

    This intentionally preserves words and numbers.

    It only normalizes formatting differences such as:
    - casing
    - whitespace
    - common quote variations
    - dash variations
    - soft hyphens
    """

    if not text:
        return ""

    text = text.replace("\u00ad", "")

    # Normalize common quote characters.
    text = (
        text.replace("“", '"')
        .replace("”", '"')
        .replace("‘", "'")
        .replace("’", "'")
    )

    # Normalize different dash characters.
    text = (
        text.replace("–", "-")
        .replace("—", "-")
        .replace("−", "-")
    )

    # Lowercase.
    text = text.lower()

    # Collapse all whitespace.
    text = re.sub(r"\s+", " ", text)

    return text.strip()


def normalize_for_matching(text: str) -> str:
    """
    More tolerant normalization used only for fuzzy evidence matching.

    It keeps letters and numbers, but removes punctuation that can differ
    between PDF extraction and Gemini's copied evidence.
    """

    text = normalize_text(text)

    # Keep unicode letters/numbers and spaces.
    text = re.sub(
        r"[^\w\s₹]",
        " ",
        text,
        flags=re.UNICODE,
    )

    text = re.sub(r"\s+", " ", text)

    return text.strip()


# ============================================================================
# PDF TEXT EXTRACTION
# ============================================================================

def extract_pdf_pages(
    file_bytes: bytes,
) -> List[ExtractedPage]:
    """
    Extract text page-by-page.

    Keeping page boundaries is important because later we need to know
    where Gemini's evidence actually occurs.
    """

    pages: List[ExtractedPage] = []

    with pdfplumber.open(io.BytesIO(file_bytes)) as pdf:
        for page_number, page in enumerate(
            pdf.pages,
            start=1,
        ):
            try:
                page_text = page.extract_text() or ""
            except Exception as e:
                print(
                    f"⚠️ PDF page {page_number} extraction failed: {e}"
                )
                page_text = ""

            page_text = page_text.strip()

            pages.append(
                ExtractedPage(
                    page_number=page_number,
                    text=page_text,
                )
            )

    return pages


def combine_pages(
    pages: List[ExtractedPage],
) -> str:
    """
    Combine page text for Gemini while preserving page boundaries.
    """

    parts: List[str] = []

    for page in pages:
        if not page.text.strip():
            continue

        parts.append(
            f"\n--- PAGE {page.page_number} ---\n"
            f"{page.text}"
        )

    return "\n".join(parts).strip()


