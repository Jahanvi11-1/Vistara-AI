# ============================================================================
# ANALYZE ENDPOINT
# ============================================================================

@app.post(
    "/analyze",
    response_model=ContractReport,
)
async def analyze_contract(
    mock: bool = Query(False),
    file: Optional[UploadFile] = File(None),
    text: Optional[str] = Form(None),
):

    # ------------------------------------------------------------------------
    # Mock mode
    # ------------------------------------------------------------------------

    if mock:
        return MOCK_REPORT

    filename = "contract.txt"
    contract_text = ""
    extracted_pages: List[ExtractedPage] = []

    # ------------------------------------------------------------------------
    # FILE UPLOAD
    # ------------------------------------------------------------------------

    if file is not None:

        filename = file.filename or "upload.pdf"

        file_bytes = await file.read()

        if not file_bytes:
            raise HTTPException(
                status_code=422,
                detail="Uploaded file is empty.",
            )

        # --------------------------------------------------------------------
        # PDF
        # --------------------------------------------------------------------

        if filename.lower().endswith(".pdf"):

            try:

                extracted_pages = extract_pdf_pages(
                    file_bytes
                )

                contract_text = combine_pages(
                    extracted_pages
                )

            except Exception as e:

                print(
                    "PDF extraction error:"
                )
                print(
                    traceback.format_exc()
                )

                raise HTTPException(
                    status_code=422,
                    detail=(
                        f"Could not read PDF: {str(e)}"
                    ),
                )

        # --------------------------------------------------------------------
        # Other readable files
        # --------------------------------------------------------------------

        else:

            contract_text = file_bytes.decode(
                "utf-8",
                errors="replace",
            ).strip()

            extracted_pages = extract_text_input(
                contract_text
            )

    # ------------------------------------------------------------------------
    # RAW TEXT
    # ------------------------------------------------------------------------

    elif text:

        filename = "contract.txt"

        contract_text = text.strip()

        extracted_pages = extract_text_input(
            contract_text
        )

    # ------------------------------------------------------------------------
    # NOTHING SUPPLIED
    # ------------------------------------------------------------------------

    else:

        raise HTTPException(
            status_code=422,
            detail=(
                "Provide either a file upload "
                "or text in the request body."
            ),
        )

    # ------------------------------------------------------------------------
    # Validate extracted text
    # ------------------------------------------------------------------------

    if not contract_text.strip():

        raise HTTPException(
            status_code=422,
            detail=(
                "Could not extract any readable text "
                "from the provided input."
            ),
        )

    # ------------------------------------------------------------------------
    # DEBUG INFORMATION
    # ------------------------------------------------------------------------

    print(
        "========================================"
    )
    print(
        "VISTARA DOCUMENT EXTRACTION"
    )
    print(
        f"Filename: {filename}"
    )
    print(
        f"Pages/logical sections: "
        f"{len(extracted_pages)}"
    )
    print(
        f"Total characters: "
        f"{len(contract_text)}"
    )
    print(
        "========================================"
    )

    for page in extracted_pages:
        print(
            f"Page {page.page_number}: "
            f"{len(page.text)} characters"
        )

    # ------------------------------------------------------------------------
    # Gemini analysis
    # ------------------------------------------------------------------------

    return await analyze_with_gemini(
        contract_text=contract_text,
        filename=filename,
        pages=extracted_pages,
    )